"""Regenerate the compact evaluation tables and SVG figure offline.

The full 10,000 x 500 study remains available through ``make simulate``.  This
reproduction target intentionally uses a bounded 24 x 2 run so it is
practical on a clean machine and still exercises the same simulator code,
parameter manifest, paired arms, sensitivity analysis, and stress scenarios.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from careloop.simulator import SimulationConfig, Simulator, load_parameters


# One source of truth for the compact reproduction run. Renderers below read
# the generated JSON config, so labels cannot drift from this setting.
REPRODUCE_CONFIG = {"cohort_size": 24, "runs": 2, "seed": 20261019, "virtual_days": 90}


def _svg(result: dict, path: Path) -> None:
    arms = result["intervals"]["arms"]
    config = result["config"]
    arm_a = float(arms["Arm A"]["closure_rate"]["mean"])
    b_full = float(arms["B-full"]["closure_rate"]["mean"])
    width, height = 760, 360
    chart_x, chart_y, chart_w, chart_h = 100, 55, 600, 230
    scale = chart_h
    bars = [("Arm A", arm_a, "#6f7b8d"), ("B-full", b_full, "#16a38c")]
    elements = [
        f'<svg xmlns="http://www.w3.org/2000/svg" width="{width}" height="{height}" viewBox="0 0 {width} {height}">',
        '<rect width="100%" height="100%" fill="#f7f9fb"/>',
        '<text x="100" y="30" font-family="Arial" font-size="18" font-weight="700" fill="#17324d">Model-conditional closure rate</text>',
        f'<line x1="{chart_x}" y1="{chart_y + chart_h}" x2="{chart_x + chart_w}" y2="{chart_y + chart_h}" stroke="#9aa8b6"/>',
        f'<line x1="{chart_x}" y1="{chart_y}" x2="{chart_x}" y2="{chart_y + chart_h}" stroke="#9aa8b6"/>',
        f'<text x="100" y="330" font-family="Arial" font-size="12" fill="#526274">{config["cohort_size"]} cases × {config["runs"]} paired runs; synthetic parameters only</text>',
    ]
    for index, (label, value, colour) in enumerate(bars):
        x = 220 + index * 230
        bar_h = max(1, value * scale)
        y = chart_y + chart_h - bar_h
        elements.append(f'<rect x="{x}" y="{y:.1f}" width="110" height="{bar_h:.1f}" rx="8" fill="{colour}"/>')
        elements.append(f'<text x="{x + 55}" y="{y - 10:.1f}" text-anchor="middle" font-family="Arial" font-size="16" font-weight="700" fill="#17324d">{value:.3f}</text>')
        elements.append(f'<text x="{x + 55}" y="{chart_y + chart_h + 26}" text-anchor="middle" font-family="Arial" font-size="14" fill="#526274">{label}</text>')
    elements.append("</svg>")
    path.write_text("\n".join(elements) + "\n", encoding="utf-8")


def main() -> int:
    parser = argparse.ArgumentParser(description="Reproduce CareLoop evaluation outputs")
    parser.add_argument("--output", type=Path, default=Path("out"))
    args = parser.parse_args()
    args.output.mkdir(parents=True, exist_ok=True)
    parameters = load_parameters()
    config = SimulationConfig.from_parameters(parameters, **REPRODUCE_CONFIG)
    result = Simulator(config, parameters).run(include_sensitivity=True, include_stress=True)
    json_path = args.output / "reproduce.json"
    csv_path = args.output / "reproduce.csv"
    svg_path = args.output / "closure-rate.svg"
    table_path = args.output / "evaluation-table.md"
    result.write_json(json_path)
    result.write_csv(csv_path)
    # Read back the generated artifact so every derived output uses the actual
    # simulator configuration and arm names written to JSON.
    payload = json.loads(json_path.read_text(encoding="utf-8"))
    _svg(payload, svg_path)
    arms = payload["intervals"]["arms"]
    delta = payload["paired_differences"]
    table = [
        "# Generated evaluation table",
        "",
        f"This table is generated by `scripts/reproduce.py`; it is model-conditional and uses assumption-only parameters ({payload['config']['cohort_size']} cases × {payload['config']['runs']} paired runs).",
        "",
        "| Arm | Closure rate mean | 95% interval | Owner coverage mean | Teach-back mean |",
        "|---|---:|---:|---:|---:|",
    ]
    for arm in ("Arm A", "B-full"):
        row = arms[arm]
        table.append(f"| {arm} | {row['closure_rate']['mean']:.4f} | [{row['closure_rate']['lower']:.4f}, {row['closure_rate']['upper']:.4f}] | {row['owner_coverage_rate']['mean']:.4f} | {row['teach_back_rate']['mean']:.4f} |")
    table.extend([
        "",
        f"Paired closure-rate delta (B-full minus Arm A), run means: `{json.dumps([row.get('closure_rate_delta') for row in delta])}`.",
        "",
        "The figure is a workflow simulation output, not evidence of clinical effectiveness.",
    ])
    table_path.write_text("\n".join(table) + "\n", encoding="utf-8")
    print(f"Reproduced: {json_path}")
    print(f"Reproduced: {csv_path}")
    print(f"Reproduced: {svg_path}")
    print(f"Reproduced: {table_path}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
